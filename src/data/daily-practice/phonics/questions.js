// 從題庫中隨機選擇指定數量的題目
export const getQuestions = (categoryId, count = 10) => {
  let allQuestions = []
  
  // 處理綜合練習
  if (categoryId === 'basic-mixed') {
    // 基礎綜合：所有短母音 + 長母音
    const basicCategories = [
      'short-a', 'short-e', 'short-i', 'short-o', 'short-u',
      'long-a', 'long-e', 'long-i', 'long-o', 'long-u'
    ]
    basicCategories.forEach(cat => {
      if (phonicsQuestions[cat]) {
        allQuestions = allQuestions.concat(phonicsQuestions[cat])
      }
    })
  } else if (categoryId === 'advanced-mixed') {
    // 進階綜合：所有雙字母 + 子音組合
    const advancedCategories = [
      'digraph-ch', 'digraph-sh', 'digraph-th', 'digraph-wh', 'digraph-ph',
      'blend-bl', 'blend-br', 'blend-st'
    ]
    advancedCategories.forEach(cat => {
      if (phonicsQuestions[cat]) {
        allQuestions = allQuestions.concat(phonicsQuestions[cat])
      }
    })
  } else if (categoryId === 'all-mixed') {
    // 全部綜合：所有分類
    const allCategories = [
      'short-a', 'short-e', 'short-i', 'short-o', 'short-u',
      'long-a', 'long-e', 'long-i', 'long-o', 'long-u',
      'digraph-ch', 'digraph-sh', 'digraph-th', 'digraph-wh', 'digraph-ph',
      'blend-bl', 'blend-br', 'blend-st'
    ]
    allCategories.forEach(cat => {
      if (phonicsQuestions[cat]) {
        allQuestions = allQuestions.concat(phonicsQuestions[cat])
      }
    })
  } else {
    // 一般分類
    allQuestions = phonicsQuestions[categoryId] || []
  }
  
  if (allQuestions.length === 0) {
    return []
  }
  
  // 隨機打亂並取前 N 題
  const shuffled = [...allQuestions].sort(() => Math.random() - 0.5)
  const selected = shuffled.slice(0, Math.min(count, shuffled.length))
  
  // 打亂每題的選項順序
  return selected.map(q => {
    const correctWord = q.options[q.answer]  // 記住正確答案的文字
    
    // 打亂選項順序
    const shuffledOptions = [...q.options].sort(() => Math.random() - 0.5)
    
    // 找出正確答案在新順序中的位置
    const newAnswerIndex = shuffledOptions.indexOf(correctWord)
    
    return {
      word: q.word,
      options: shuffledOptions,
      answer: newAnswerIndex
    }
  })
}

export default phonicsQuestions
